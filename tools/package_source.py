#!/usr/bin/env python3
"""Fail-closed source packaging: only explicitly reviewed text files can ship.

Do not use this to package a playable build. Binary release packaging needs a
separate policy for original runtime binaries and third-party notices.
"""
from __future__ import annotations
import argparse
import json
import re
import subprocess
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ALLOWLIST = ROOT / "configs/source_package.json"
DENIED_PARTS = {"disc", "generated", "cache", "saves", ".local", "upload", "executables", "__pycache__", ".git"}
DENIED_SUFFIXES = {".bin", ".cue", ".iso", ".chd", ".exe", ".dll", ".vpk", ".elf", ".self", ".psp2dmp",
                   ".tim", ".tmd", ".trm", ".snd", ".sxa", ".str", ".raw", ".wav", ".ogg", ".mp3", ".flac"}


def validate_file(root: Path, relative: str) -> bytes:
    path = root / relative
    rel = Path(relative)
    if rel.is_absolute() or ".." in rel.parts or any(p.lower() in DENIED_PARTS for p in rel.parts):
        raise ValueError(f"Forbidden source path: {relative}")
    if path.suffix.lower() in DENIED_SUFFIXES or path.is_symlink() or not path.is_file():
        raise ValueError(f"Forbidden or missing source file: {relative}")
    if not path.resolve().is_relative_to(root.resolve()):
        raise ValueError(f"Source path escapes the project: {relative}")
    if path.stat().st_size > 128 * 1024:
        raise ValueError(f"Unexpectedly large source file: {relative}")
    data = path.read_bytes()
    text = data.decode("utf-8")
    if b"\0" in data or data.startswith(b"PS-X EXE"):
        raise ValueError(f"Binary content in source package: {relative}")
    # Detect emitter output even when renamed to an allowed filename.
    if re.search(r"(?:void\s+func_[0-9A-Fa-f]{8}\s*\(|Generated by PSXRecomp\s*-|bytes_b64\s*[\"']?\s*:)", text):
        raise ValueError(f"Generated game content in source package: {relative}")
    return data


def collect(root: Path) -> dict[str, bytes]:
    names = json.loads((root / "configs/source_package.json").read_text())
    if not isinstance(names, list) or len(names) != len(set(names)):
        raise ValueError("Invalid source package allowlist")
    return {name: validate_file(root, name) for name in names}


def audit_staging(root: Path, allowed: set[str]):
    # A release stage must contain exactly the files allowed by this policy.
    actual = {str(p.relative_to(root)).replace("\\", "/") for p in root.rglob("*") if p.is_file() or p.is_symlink()}
    if actual != allowed:
        raise ValueError(f"Unexpected or missing release files: {sorted(actual ^ allowed)}")
    for name in sorted(actual):
        validate_file(root, name)


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--output", type=Path)
    p.add_argument("--check-stage", type=Path)
    p.add_argument("--check-tracked", action="store_true")
    args = p.parse_args()
    try:
        files = collect(ROOT)
        if args.check_tracked:
            tracked = subprocess.check_output(["git", "ls-files", "-z"], cwd=ROOT).decode("utf-8").split("\0")
            unexpected = set(filter(None, tracked)) - set(files)
            if unexpected:
                raise ValueError(f"Unreviewed tracked files: {sorted(unexpected)}")
        if args.check_stage:
            audit_staging(args.check_stage, set(files))
        if args.output:
            args.output.parent.mkdir(parents=True, exist_ok=True)
            with zipfile.ZipFile(args.output, "w", zipfile.ZIP_DEFLATED) as z:
                for name, data in sorted(files.items()):
                    z.writestr("Nitrogen-Squared/" + name, data)
        print(f"Source package audit passed: {len(files)} reviewed text files; no game payloads.")
    except (ValueError, OSError) as e:
        p.exit(1, f"Package rejected: {e}\n")


if __name__ == "__main__":
    main()
